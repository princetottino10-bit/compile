/* =========================================================================
 * コントロールの紋章 (角を落とした三角形に、三方へ腕の伸びた窓と中心の丸)
 *   Main 3 の公式の裏面とコントロールコンポーネントのカードに同じ形が描かれている。
 *   3D のマーカー (control.js) と裏面 (cardtex.js) の両方で使うので、形はここだけに置く。
 *   単位は外形の半径 ≈ 0.42、y は上向き。原点は中心の丸。
 * ========================================================================= */

/* トラッカーのマーカー画像 (2048px) の輪郭を、中心をそろえて 120° 対称に整えたもの */
export const OUTER = [[-0.064, 0.415], [-0.392, -0.152], [-0.328, -0.263], [0.328, -0.263], [0.392, -0.152], [0.064, 0.415]];
export const WINDOW = [[-0.078, 0.223], [0.078, 0.223], [0.078, 0.133], [0.155, 0.001], [0.232, -0.044], [0.154, -0.179],
  [0.076, -0.135], [-0.076, -0.135], [-0.154, -0.179], [-0.232, -0.044], [-0.155, 0.001], [-0.078, 0.133]];
export const DOT_R = 0.079;

/** 紋章を塗る (窓は抜き、中心の丸は塗る)。cx, cy: 中心の丸の位置 (px)、k: 1 単位の px */
export function fillEmblem(c, cx, cy, k) {
  const P = (x, y) => [cx + x * k, cy - y * k];
  c.beginPath();
  OUTER.forEach(([x, y], i) => { const [px, py] = P(x, y); if (i) c.lineTo(px, py); else c.moveTo(px, py); });
  c.closePath();
  /* 窓は逆回りにして evenodd で抜く */
  WINDOW.slice().reverse().forEach(([x, y], i) => { const [px, py] = P(x, y); if (i) c.lineTo(px, py); else c.moveTo(px, py); });
  c.closePath();
  c.fill('evenodd');
  c.beginPath(); c.arc(cx, cy, DOT_R * k, 0, Math.PI * 2); c.fill();
}


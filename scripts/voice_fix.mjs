export const READING = [['勝った', 'かった'], ['勝ち', 'かち'], ['手札', 'てふだ'], ['積み上がって', 'つみあがって'],
  /* 2026-09-29 の見直し: 表 → ヒョウ、札 → サツ、品 → シナ、邪魔者 → ジャマシャ、一押し → イチオシ、映える → ハエル (ギャル言葉のバエる) */
  ['「表」', 'おもて'], ['表で', 'おもてで'], ['真ん中の札', 'まんなかのふだ'], ['品のない', 'ひんのない'],
  ['邪魔者', '邪魔もの'], ['一押し', 'ひとおし'], ['映える', 'バエる'], ['分が悪い', 'ぶがわるい']];
export const fixReading = (t) => READING.reduce((s, [a, b]) => s.split(a).join(b), t);
